let cachedDb: PlatformDatabase | null = null;

export function getDb(): PlatformDatabase {
  if (cachedDb) return cachedDb;
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (fs.existsSync(DB_FILE)) {
    try {
      const raw = fs.readFileSync(DB_FILE, 'utf-8');
      cachedDb = JSON.parse(raw) as PlatformDatabase;
      return cachedDb;
    } catch {
      // fall through to re-seed if file corrupted
    }
  }
  cachedDb = createInitialDatabase();
  saveDb(cachedDb);
  return cachedDb;
}

